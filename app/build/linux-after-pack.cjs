// electron-builder afterPack hook (package.json > build.afterPack).
//
// On recent Ubuntu/Mint, AppArmor blocks the unprivileged user namespaces
// Chromium's sandbox needs, and an AppImage can't ship the setuid-root
// chrome-sandbox fallback either, so Electron aborts on startup. Passing
// --no-sandbox from main.ts is too late (Chromium checks before any JS runs),
// so on Linux the real binary is renamed to "<name>.bin" and replaced with a
// launcher script that adds --no-sandbox only when no sandbox can work.
// Runs before the AppImage/.deb targets are built, so both get the launcher.
const fs = require("fs/promises");
const path = require("path");

module.exports = async function afterPack(context) {
  if (context.electronPlatformName !== "linux") return;

  const name = context.packager.executableName;
  const executable = path.join(context.appOutDir, name);
  await fs.rename(executable, `${executable}.bin`);

  const launcher = `#!/bin/bash
# Launcher generated by build/linux-after-pack.cjs: starts ${name}.bin with
# Chromium's sandbox when the system allows it, with --no-sandbox otherwise.
HERE="$(dirname "$(readlink -f "$0")")"
BIN="$HERE/${name}.bin"

sandbox_available() {
  # setuid-root helper (set up by the .deb install) -> Chromium's SUID sandbox
  local helper="$HERE/chrome-sandbox"
  if [ -u "$helper" ] && [ "$(stat -c %u "$helper")" = "0" ]; then
    return 0
  fi
  # Otherwise Chromium needs unprivileged user namespaces (restricted by AppArmor on Ubuntu 23.10+)
  unshare --user --map-root-user true 2>/dev/null
}

if sandbox_available; then
  exec "$BIN" "$@"
fi
exec "$BIN" --no-sandbox "$@"
`;

  await fs.writeFile(executable, launcher, { mode: 0o755 });
};
